                item('CoordRangeZ', [], 'numeric', 'chunk.coordRangeZ', 'Z range [min max]'), ...
                item('GradientVariable', '', 'text', 'chunk.gradientVariable', 'Target field for Variable=gradient'), ...
                item('GradientSmoothLevel', 0, 'numeric', 'chunk.gradientSmoothLevel', 'Gaussian smoothing sigma before 1D differentiation'), ...
                item('StrainRateVelocityComponent', 'vz', 'text', 'chunk.strainRateVelocityComponent', 'Velocity field used by 1D strain rate'), ...
                item('StrainRateDensityVariable', 'c_rho', 'text', 'chunk.strainRateDensityVariable', 'Density field used by 1D strain rate')];

        case 'cluster'
            catalog = [ ...
                item('Dim', 2, 'numeric', 'analysis', 'Spatial dimension: 2 or 3'), ...
                item('Dx', 1, 'numeric', 'analysis', 'Particle spacing'), ...
                item('ParticleVolume', [], 'numeric', 'analysis', 'Explicit per-particle volume for Dim=3'), ...
                item('ThinDirectionThickness', [], 'numeric', 'analysis', 'Thickness for quasi-2D projection'), ...
                item('NcountVar', 'Ncount', 'text', 'analysis', 'Cluster count column'), ...
                item('Range_c_x', [], 'numeric', 'analysis', 'Centroid X range'), ...
                item('Range_c_y', [], 'numeric', 'analysis', 'Centroid Y range'), ...
                item('Range_c_z', [], 'numeric', 'analysis', 'Centroid Z range'), ...
                item('Range_vx', [], 'numeric', 'analysis', 'Velocity X range'), ...
                item('Range_vy', [], 'numeric', 'analysis', 'Velocity Y range'), ...
                item('Range_vz', [], 'numeric', 'analysis', 'Velocity Z range'), ...
                item('DiameterRange', [], 'numeric', 'analysis', 'Equivalent diameter range'), ...
                item('XVarForMean', 'c_x', 'text', 'analysis', 'Variable used for binned means'), ...
                item('MeanNumBins', 20, 'numeric', 'analysis', 'Number of position bins'), ...
                item('MeanPowerM', 1, 'numeric', 'analysis', 'Generalized mean numerator power'), ...
                item('MeanPowerN', 0, 'numeric', 'analysis', 'Generalized mean denominator power'), ...
                item('DiameterHistBinSize', [], 'numeric', 'analysis', 'Diameter histogram bin width'), ...
                item('DiameterEmptyBinMode', 'zero', 'text', 'analysis', 'zero, nan, or remove'), ...
                item('DiameterPlotStyle', 'bar', 'text', 'analysis', 'bar or scatter'), ...
                item('DiameterFitTypes', {'powerlaw','gamma','lognormal'}, 'celltext', 'analysis', 'Comma-separated fit types'), ...
                item('HistScale', 'linear', 'text', 'analysis', 'linear, semilogx, semilogy, or loglog')];

        case 'vx'
            catalog = [ ...
                item('VelocityVar', 'auto', 'text', 'analysis', 'auto tries Coord1 then Chunk'), ...
                item('VelocityFactor', 0.001, 'numeric', 'analysis', 'Manual coordinate-to-km/s factor'), ...
                item('DensityFactor', 1, 'numeric', 'analysis', 'Manual areal-density-to-mg/cm^2 factor'), ...
                item('UseFileUnitMetadata', true, 'logical', 'analysis', 'Use SPID Units metadata when available'), ...
                item('VelocityLabel', 'Velocity', 'text', 'analysis', 'Velocity axis label'), ...
                item('VelocityUnit', 'km/s', 'text', 'analysis', 'Velocity axis unit'), ...
                item('CumulativeDirection', 'high-to-low', 'text', 'analysis', 'high-to-low or low-to-high'), ...
                item('NegativeDensityMode', 'clip', 'text', 'analysis', 'clip or reject negative areal-density values'), ...
                item('DensityVars', {}, 'celltext', 'analysis', 'Comma-separated density columns; empty means auto')];

        case 'massx'
            catalog = [ ...
                item('ChunkDim', 'auto', 'text', 'analysis', 'SPH chunk dimension: auto, 1d, or 2d'), ...
                item('CoordinateVar', 'auto', 'text', 'analysis', 'Coordinate column; auto tries Coord1, c_x, then Chunk'), ...
                item('CoordinateVarY', 'auto', 'text', 'analysis', 'Y column for bin2d; auto tries Coord2 then c_y'), ...
                item('NcountVar', 'Ncount', 'text', 'analysis', 'SPH particle-count column'), ...
                item('SphDimension', 2, 'numeric', 'analysis', 'Physical SPH dimension: 2 or 3'), ...
                item('InitialDensity', [], 'numeric', 'analysis', 'Initial SPH material density in g/cm^3'), ...
                item('ParticleSpacing', [], 'numeric', 'analysis', 'Initial SPH particle spacing d0 in raw coordinate units'), ...
