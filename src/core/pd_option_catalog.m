% MATLAB R2016b compatible. GUI and scripts share this single definition.

    analysisType = pd_normalize_analysis_type(analysisType);
    switch analysisType
        case 'chunk'
            catalog = [ ...
                item('ChunkDim', 'auto', 'text', 'chunk.dimension', 'auto, 1d, 2d, or 3d'), ...
