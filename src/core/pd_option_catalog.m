                item('PositionRangeY', [], 'numeric', 'analysis', 'Component Y range'), ...
                item('PlotRangeX', [], 'numeric', 'analysis', 'Computed plot X range'), ...
                item('PlotRangeY', [], 'numeric', 'analysis', 'Computed plot Y range'), ...
