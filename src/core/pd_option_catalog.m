                item('SliceWidthsY', [], 'numeric', 'analysis', 'Scalar or per-slice bin2d y widths in raw units'), ...
                item('CoordinateFactor', 10, 'numeric', 'analysis', 'Display coordinate multiplier; normally 10 for um'), ...
                item('CoordinateRange', [], 'numeric', 'analysis', 'Coordinate range after conversion [min max]'), ...
