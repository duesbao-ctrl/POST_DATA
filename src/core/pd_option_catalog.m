                item('CumulativeDirection', 'high-to-low', 'text', 'analysis', 'Fixed high-to-low so cumulative mass-x decreases with x')];

        case 'network2d'
            catalog = [ ...
                item('ThresholdN', 1, 'numeric', 'analysis', 'Pore when Ncount is below this value'), ...
